    public string Get(GuildSettings settings, string key)
    {
        var language = string.IsNullOrWhiteSpace(settings.Language) ? "en" : settings.Language;
        if (Texts.TryGetValue(language, out var selected) && selected.TryGetValue(key, out var value))
        {
            return value;
        }

        return Texts["en"].GetValueOrDefault(key, key);
    }

    public string Format(GuildSettings settings, string key, IReadOnlyDictionary<string, string> values)
    {
        var text = Get(settings, key);
        foreach (var (name, value) in values)
        {
            text = text.Replace("{" + name + "}", value, StringComparison.OrdinalIgnoreCase);
        }

        return text;
    }
